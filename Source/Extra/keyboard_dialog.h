// BUTTON FUNCTIONS

"proc ::dialog_keyboard::cancel {id} {\n"
"    pdsend \"$id cancel\"\n"
"}\n"
"\n"

"proc ::dialog_keyboard::ok {id} {\n"
"    ::dialog_keyboard::apply $id\n"
"    ::dialog_keyboard::cancel $id\n"
"}\n"
"\n"

"proc ::dialog_keyboard::apply {id} {\n"
"    set vid [string trimleft $id .]\n"
"\n"
// symbol names (default 'empty' if blank)
"    set snd_name empty\n"
"    set rcv_name empty\n"
"    if {$::dialog_keyboard::var_snd($vid) ne \"\"} {set snd_name $::dialog_keyboard::var_snd($vid)}\n"
"    if {$::dialog_keyboard::var_rcv($vid) ne \"\"} {set rcv_name $::dialog_keyboard::var_rcv($vid)}\n"
"\n"
// clip numeric values to match C-side limits
"    set ::dialog_keyboard::var_width($vid)   [::dialog_keyboard::clip $::dialog_keyboard::var_width($vid)   7]\n"
"    set ::dialog_keyboard::var_height($vid)  [::dialog_keyboard::clip $::dialog_keyboard::var_height($vid) 10]\n"
"    set ::dialog_keyboard::var_octaves($vid) [::dialog_keyboard::clip $::dialog_keyboard::var_octaves($vid)  1 10]\n"
"    set ::dialog_keyboard::var_low_c($vid)   [::dialog_keyboard::clip $::dialog_keyboard::var_low_c($vid)    0  8]\n"
"    set ::dialog_keyboard::var_norm($vid)    [::dialog_keyboard::clip $::dialog_keyboard::var_norm($vid)     0 127]\n"
"\n"
// send to the object
"    pdsend [concat $id dialog \\\n"
"                $::dialog_keyboard::var_width($vid)   \\\n"
"                $::dialog_keyboard::var_height($vid)  \\\n"
"                $::dialog_keyboard::var_octaves($vid) \\\n"
"                $::dialog_keyboard::var_low_c($vid)   \\\n"
"                $::dialog_keyboard::var_norm($vid)    \\\n"
"                $::dialog_keyboard::var_tgl($vid)     \\\n"
"                [::dialog_keyboard::sanitize $snd_name] \\\n"
"                [::dialog_keyboard::sanitize $rcv_name] \\\n"
"            ]\n"
"}\n"
"\n"

"proc ::dialog_keyboard::bind_enter_to_apply {id} {\n"
"    ::dialog_keyboard::apply $id\n"
"    bind $id <KeyPress-Return> \"::dialog_keyboard::ok $id\"\n"
"    focus $id.cao.ok\n"
"    return 0\n"
"}\n"
"\n"

"proc ::dialog_keyboard::unbind_return {id} {\n"
"    bind $id <KeyPress-Return> break\n"
"    return 1\n"
"}\n";
